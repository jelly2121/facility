-- PROFILES POLICIES

CREATE POLICY "Users view own profile or admin views all"
ON public.profiles FOR SELECT
TO authenticated
USING (
    id = (SELECT auth.uid())
    OR (SELECT public.current_user_role()) = 'Administrator'
);

CREATE POLICY "Admin updates profiles"
ON public.profiles FOR UPDATE
TO authenticated
USING (
    (SELECT public.current_user_role()) = 'Administrator'
)
WITH CHECK (
    role IN ('Administrator', 'Facility Staff', 'student')
);


-- FACILITY POLICIES

CREATE POLICY "Authenticated users view facilities"
ON public.facilities FOR SELECT
TO authenticated
USING (true);

CREATE POLICY "Admin manages facilities"
ON public.facilities FOR ALL
TO authenticated
USING (
    (SELECT public.current_user_role()) = 'Administrator'
)
WITH CHECK (
    (SELECT public.current_user_role()) = 'Administrator'
);


-- RESERVATION POLICIES

CREATE POLICY "Users view permitted reservations"
ON public.reservations FOR SELECT
TO authenticated
USING (
    user_id = (SELECT auth.uid())
    OR (SELECT public.current_user_role()) IN
       ('Administrator', 'Facility Staff')
);

CREATE POLICY "Student submits reservation"
ON public.reservations FOR INSERT
TO authenticated
WITH CHECK (
    user_id = (SELECT auth.uid())
    AND status = 'Pending'
    AND (SELECT public.current_user_role()) = 'Student'
);

CREATE POLICY "Student updates own pending reservation"
ON public.reservations FOR UPDATE
TO authenticated
USING (
    user_id = (SELECT auth.uid())
    AND status = 'Pending'
    AND (SELECT public.current_user_role()) = 'Student'
)
WITH CHECK (
    user_id = (SELECT auth.uid())
    AND status = 'Pending'
);

CREATE POLICY "Admin manages reservations"
ON public.reservations FOR ALL
TO authenticated
USING (
    (SELECT public.current_user_role()) = 'Administrator'
)
WITH CHECK (
    (SELECT public.current_user_role()) = 'Administrator'
);

CREATE POLICY "Staff updates reservation status"
ON public.reservations FOR UPDATE
TO authenticated
USING (
    (SELECT public.current_user_role()) = 'Facility Staff'
)
WITH CHECK (
    (SELECT public.current_user_role()) = 'Facility Staff'
);


-- AUDIT LOG POLICIES

CREATE POLICY "Admin views audit logs"
ON public.audit_logs FOR SELECT
TO authenticated
USING (
    (SELECT public.current_user_role()) = 'Administrator'
);


