    WHERE email = 'admin@gmail.com'
);


-- Automatically create requester profile on signup

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    INSERT INTO public.profiles (id, full_name, role)
    VALUES (
        NEW.id,
        COALESCE(NEW.raw_user_meta_data->>'full_name', ''),
        'Administrator'
    );
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;

CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();


-- 2. ROLE CHECK FUNCTION

CREATE OR REPLACE FUNCTION public.current_user_role()
RETURNS TEXT
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT role
    FROM public.profiles
    WHERE id = (SELECT auth.uid())
$$;


-- 3. FACILITIES TABLE

CREATE TABLE IF NOT EXISTS public.facilities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    location TEXT,
    capacity INTEGER DEFAULT 1,
    description TEXT,
    status TEXT NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'Maintenance', 'Inactive')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);


-- 4. RESERVATIONS TABLE

CREATE TABLE IF NOT EXISTS public.reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id),
    facility_id BIGINT NOT NULL REFERENCES public.facilities(id),
    purpose TEXT NOT NULL,
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ NOT NULL,
    status TEXT NOT NULL DEFAULT 'Pending'
        CHECK (status IN (
            'Pending',
            'Approved',
            'Rejected',
            'Scheduled',
            'In Use',
            'Completed',
            'Cancelled'
        )),
    remarks TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),

    CONSTRAINT valid_reservation_time
    CHECK (start_time < end_time)
);


-- 5. AUDIT LOGS

CREATE TABLE IF NOT EXISTS public.audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID,
    action TEXT NOT NULL,
    table_name TEXT NOT NULL,
    record_id TEXT,
    details JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW()
);


-- 6. PREVENT OVERLAPPING APPROVED RESERVATIONS

CREATE EXTENSION IF NOT EXISTS btree_gist;

ALTER TABLE public.reservations
DROP CONSTRAINT IF EXISTS no_overlapping_reservations;

ALTER TABLE public.reservations
ADD CONSTRAINT no_overlapping_reservations
EXCLUDE USING gist (
    facility_id WITH =,
    tstzrange(start_time, end_time, '[)') WITH &&
)
WHERE (
    status IN ('Approved', 'Scheduled', 'In Use')
);


-- 7. RESERVATION BUSINESS RULES

CREATE OR REPLACE FUNCTION public.validate_reservation()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    facility_status TEXT;
    user_role TEXT;
BEGIN

    SELECT status INTO facility_status
    FROM public.facilities
    WHERE id = NEW.facility_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Facility does not exist.';
    END IF;

    -- Facility must be active
    IF facility_status <> 'Active' THEN
        RAISE EXCEPTION 'Facility is not available for reservation.';
    END IF;

    -- Valid time
    IF NEW.start_time >= NEW.end_time THEN
        RAISE EXCEPTION 'Start time must be earlier than end time.';
    END IF;

    -- Completed reservations cannot be edited
    IF TG_OP = 'UPDATE' AND OLD.status = 'Completed' THEN
        RAISE EXCEPTION 'Completed reservations cannot be edited.';
    END IF;

    -- Rejected reservations cannot become scheduled
    IF TG_OP = 'UPDATE'
       AND OLD.status = 'Rejected'
       AND NEW.status = 'Scheduled' THEN
        RAISE EXCEPTION 'Rejected reservations cannot be scheduled.';
    END IF;

    -- Requester can only modify own pending requests
    IF TG_OP = 'UPDATE' THEN
        user_role := public.current_user_role();

        IF user_role = 'administrator'
           AND (
               OLD.user_id <> (SELECT auth.uid())
               OR OLD.status <> 'Pending'
               OR NEW.status <> OLD.status
           ) THEN
            RAISE EXCEPTION 'Administratoe can only edit their own pending requests.';
        END IF;
    END IF;

    NEW.updated_at := NOW();

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS reservation_validation ON public.reservations;

CREATE TRIGGER reservation_validation
BEFORE INSERT OR UPDATE ON public.reservations
FOR EACH ROW
EXECUTE FUNCTION public.validate_reservation();


-- 8. AUTOMATIC AUDIT LOGGING

CREATE OR REPLACE FUNCTION public.log_reservation_changes()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN

    IF TG_OP = 'INSERT' THEN
        INSERT INTO public.audit_logs
        (user_id, action, table_name, record_id, details)
        VALUES (
            (SELECT auth.uid()),
            'RESERVATION SUBMITTED',
            'reservations',
            NEW.id::TEXT,
            to_jsonb(NEW)
        );

        RETURN NEW;

    ELSIF TG_OP = 'UPDATE' THEN

        INSERT INTO public.audit_logs
        (user_id, action, table_name, record_id, details)
        VALUES (
            (SELECT auth.uid()),
            CASE
                WHEN NEW.status = 'Approved' THEN 'RESERVATION APPROVED'
                WHEN NEW.status = 'Rejected' THEN 'RESERVATION REJECTED'
                WHEN NEW.status = 'Cancelled' THEN 'RESERVATION CANCELLED'
                WHEN NEW.status <> OLD.status THEN 'STATUS CHANGED'
                ELSE 'RESERVATION UPDATED'
            END,
            'reservations',
            NEW.id::TEXT,
            jsonb_build_object(
                'old_status', OLD.status,
                'new_status', NEW.status,
                'reservation', to_jsonb(NEW)
            )
        );

        RETURN NEW;

    ELSIF TG_OP = 'DELETE' THEN

        INSERT INTO public.audit_logs
        (user_id, action, table_name, record_id, details)
        VALUES (
            (SELECT auth.uid()),
            'RESERVATION DELETED',
            'reservations',
            OLD.id::TEXT,
            to_jsonb(OLD)
        );

        RETURN OLD;
    END IF;

    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS reservation_audit ON public.reservations;

CREATE TRIGGER reservation_audit
AFTER INSERT OR UPDATE OR DELETE ON public.reservations
FOR EACH ROW
EXECUTE FUNCTION public.log_reservation_changes();


-- 9. FACILITY AUDIT LOGGING

CREATE OR REPLACE FUNCTION public.log_facility_changes()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    INSERT INTO public.audit_logs
    (user_id, action, table_name, record_id, details)
    VALUES (
        (SELECT auth.uid()),
        CASE
            WHEN TG_OP = 'INSERT' THEN 'FACILITY CREATED'
            WHEN TG_OP = 'UPDATE' THEN 'FACILITY UPDATED'
            WHEN TG_OP = 'DELETE' THEN 'FACILITY DELETED'
        END,
        'facilities',
        CASE
            WHEN TG_OP = 'DELETE' THEN OLD.id::TEXT
            ELSE NEW.id::TEXT
        END,
        CASE
            WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD)
            ELSE to_jsonb(NEW)
        END
    );

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS facility_audit ON public.facilities;

CREATE TRIGGER facility_audit
AFTER INSERT OR UPDATE OR DELETE ON public.facilities
FOR EACH ROW
EXECUTE FUNCTION public.log_facility_changes();


